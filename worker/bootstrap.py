"""Seed a Ledger from a business profile: founders, markets, need-states, the draft
vetting standard and the business name.

    python3 -m worker.bootstrap deploy/business/chosen-local.toml           # print the SQL
    python3 -m worker.bootstrap deploy/business/chosen-local.toml --apply   # run it on DATABASE_URL

On the VPS, pipe the printed SQL into psql as the database owner (docs/runbook.md,
"Bootstrap"). This module uses the standard library only (except --apply), so it runs
from the VPS checkout without the project's virtualenv.

Idempotent and conservative: it adds what is missing and never overwrites what a founder
has since changed in the console (labels, descriptions, launches, settings). The one
exception is founders: the profile is the list of founders, so an active founder the
profile does not name is deactivated. A new business's install uses that to retire the
two founders the first migration seeds.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
import tomllib
from pathlib import Path
from typing import Any

KEY = re.compile(r"^[a-z][a-z0-9_]*$")
FOUNDER = re.compile(r"^[a-z][a-z0-9_]{1,30}$")
RESERVED_ACTORS = {"migration", "worker", "n8n", "review_console", "eval"}
EVIDENCE_KINDS = {"file", "note", "any"}


class ProfileError(ValueError):
    pass


def _lit(value: Any) -> str:
    """A SQL literal. Strings are single-quoted with quotes doubled
    (standard_conforming_strings is on in every supported Postgres)."""
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    text = str(value)
    if "\x00" in text:
        raise ProfileError("text may not contain NUL")
    return "'" + text.replace("'", "''") + "'"


def load(path: Path) -> dict[str, Any]:
    with path.open("rb") as fh:
        profile = tomllib.load(fh)
    validate(profile)
    return profile


def validate(p: dict[str, Any]) -> None:
    name = str(p.get("business", {}).get("name", "")).strip()
    if not name:
        raise ProfileError("[business] name is required")
    founders = [f.get("name", "") for f in p.get("founders", [])]
    if not founders:
        raise ProfileError("at least one [[founders]] entry is required")
    for f in founders:
        if not FOUNDER.match(f) or f in RESERVED_ACTORS:
            raise ProfileError(f"founder name {f!r} must be lowercase letters/digits, not reserved")
    markets = p.get("markets", [])
    if not markets:
        raise ProfileError("at least one [[markets]] entry is required")
    market_keys = set()
    for m in markets:
        if not KEY.match(m.get("key", "")) or not m.get("name") or not m.get("time_zone"):
            raise ProfileError("each market needs key (lowercase), name and time_zone")
        market_keys.add(m["key"])
    for n in p.get("need_states", []):
        if not KEY.match(n.get("key", "")) or not n.get("label"):
            raise ProfileError("each need-state needs key (lowercase) and label")
        unknown = set(n.get("launch_in", [])) - market_keys
        if unknown:
            raise ProfileError(
                f"need-state {n['key']} launches in unknown markets {sorted(unknown)}"
            )
    vs = p.get("vetting_standard")
    if vs:
        if not isinstance(vs.get("version"), int) or vs["version"] < 1 or not vs.get("title"):
            raise ProfileError("[vetting_standard] needs version (1 or more) and title")
        keys = [i.get("key", "") for i in vs.get("items", [])]
        if not keys or len(set(keys)) != len(keys) or not all(KEY.match(k) for k in keys):
            raise ProfileError("[[vetting_standard.items]] need unique lowercase keys")
        for i in vs["items"]:
            if not i.get("label") or i.get("evidence_kind", "any") not in EVIDENCE_KINDS:
                raise ProfileError(
                    f"vetting item {i['key']} needs a label and a valid evidence_kind"
                )


def to_sql(p: dict[str, Any]) -> str:
    out = [
        "-- Generated by python3 -m worker.bootstrap from a business profile. Idempotent.",
        "BEGIN;",
        "SELECT set_config('app.actor', 'migration', true);",
        "",
        "-- Founders: add or reactivate those named, deactivate any other.",
    ]
    names = [f["name"] for f in p["founders"]]
    for n in names:
        out.append(
            f"INSERT INTO actors (kind, name) VALUES ('founder', {_lit(n)})\n"
            "  ON CONFLICT (name) DO UPDATE SET active = true\n"
            "  WHERE actors.kind = 'founder' AND NOT actors.active;"
        )
    out.append(
        "UPDATE actors SET active = false WHERE kind = 'founder' AND active\n"
        f"  AND name NOT IN ({', '.join(_lit(n) for n in names)});"
    )
    out.append("DO $$ BEGIN")
    for n in names:
        out.append(
            f"  IF NOT EXISTS (SELECT 1 FROM actors WHERE name = {_lit(n)}\n"
            "                 AND kind = 'founder') THEN\n"
            f"    RAISE EXCEPTION 'actor % exists and is not a founder', {_lit(n)};\n"
            "  END IF;"
        )
    out.append("END $$;")

    out += ["", "-- Business name (kept if a founder has changed it)."]
    out.append(
        "INSERT INTO settings (key, value) VALUES "
        f"('core.business_name', to_jsonb({_lit(p['business']['name'].strip())}::text))\n"
        "  ON CONFLICT (key) DO NOTHING;"
    )

    out += ["", "-- Markets."]
    for m in p["markets"]:
        out.append(
            "INSERT INTO markets (key, name, time_zone) VALUES "
            f"({_lit(m['key'])}, {_lit(m['name'])}, {_lit(m['time_zone'])})\n"
            "  ON CONFLICT (key) DO NOTHING;"
        )

    out += ["", "-- Need-states, and where each is launched (marketed)."]
    for i, n in enumerate(p.get("need_states", [])):
        out.append(
            "INSERT INTO need_states (key, label, description, covers, not_covered, sort_order)\n"
            f"  VALUES ({_lit(n['key'])}, {_lit(n['label'])}, {_lit(n.get('description'))}, "
            f"{_lit(n.get('covers'))}, {_lit(n.get('not_covered'))}, "
            f"{_lit(int(n.get('sort_order', (i + 1) * 10)))})\n"
            "  ON CONFLICT (key) DO NOTHING;"
        )
        for market in n.get("launch_in", []):
            out.append(
                "INSERT INTO market_need_states (market_key, need_state_key) VALUES "
                f"({_lit(market)}, {_lit(n['key'])})\n"
                "  ON CONFLICT (market_key, need_state_key) DO NOTHING;"
            )

    vs = p.get("vetting_standard")
    if vs:
        out += ["", "-- The draft vetting standard. Items are added only while it is a draft."]
        out.append(
            "INSERT INTO vetting_standards (version, title) VALUES "
            f"({_lit(vs['version'])}, {_lit(vs['title'])})\n"
            "  ON CONFLICT (version) DO NOTHING;"
        )
        for i, item in enumerate(vs["items"]):
            out.append(
                "INSERT INTO vetting_item_types\n"
                "    (standard_id, key, label, description, evidence_kind, required, sort_order)\n"
                f"  SELECT s.id, {_lit(item['key'])}, {_lit(item['label'])}, "
                f"{_lit(item.get('description'))}, {_lit(item.get('evidence_kind', 'any'))}, "
                f"{_lit(bool(item.get('required', True)))}, {_lit((i + 1) * 10)}\n"
                f"    FROM vetting_standards s WHERE s.version = {_lit(vs['version'])} "
                "AND s.status = 'draft'\n"
                "  ON CONFLICT (standard_id, key) DO NOTHING;"
            )
    out += ["", "COMMIT;", ""]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python3 -m worker.bootstrap")
    parser.add_argument("profile", type=Path)
    parser.add_argument(
        "--apply", action="store_true", help="run the SQL on DATABASE_URL instead of printing it"
    )
    args = parser.parse_args(argv)
    try:
        sql = to_sql(load(args.profile))
    except (OSError, ProfileError, tomllib.TOMLDecodeError) as exc:
        print(f"bootstrap: {exc}", file=sys.stderr)
        return 2
    if not args.apply:
        sys.stdout.write(sql)
        return 0
    import psycopg

    url = os.environ.get("DATABASE_URL")
    if not url:
        print("bootstrap: DATABASE_URL is not set", file=sys.stderr)
        return 2
    with psycopg.connect(url, autocommit=True) as conn:
        conn.execute(sql)
    print("bootstrap: applied")
    return 0


if __name__ == "__main__":
    sys.exit(main())
